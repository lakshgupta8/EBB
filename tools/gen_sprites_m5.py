def build_props_m5(base):
    n0 = base.width // 16
    im = Image.new("RGBA", (16 * (n0 + 1), 16), (0, 0, 0, 0))
    im.alpha_composite(base, (0, 0))
    c = Canvas(16, 16)
    c.blit(FEN, 0, 0)
    im.alpha_composite(c.im, (16 * n0, 0))
    im.save(os.path.join(OUT, "props.png"))
    return im


def build_all(built):
    built["props"] = build_props_m5(built["props"])
