def main():
    os.makedirs(REF, exist_ok=True)
    built = {
        "fx_slash": build_arc("SALT_WHITE", "PALE_SLATE"),
        "fx_slash_warm": build_arc("WARM_YELLOW", "AMBER"),
        "fx_stab": strip([grid(t, 24, 8) for t in STAB]),
        "fx_spark": strip([grid(t, 12, 12) for t in SPARK]),
        "fx_crack": strip([crack_frame(f) for f in range(4)]),
        "fx_ring16": strip([ring_frame(16, f) for f in range(3)]),
        "fx_ring32": strip([ring_frame(32, f) for f in range(3)]),
        "fx_ring96": strip([ring_frame(96, f) for f in range(3)]),
        "fx_lit": strip([grid(t, 24, 24) for t in LIT]),
        "fx_stun": strip([grid(t, 16, 8) for t in STUN]),
        "fx_bleed": strip([grid(t, 8, 8) for t in BLEED]),
    }
    for name, im in built.items():
        im.save(os.path.join(SPRITES, name + ".png"))

    # --- review sheet ---
    try:
        font = ImageFont.load_default(size=11)
        small = ImageFont.load_default(size=9)
    except TypeError:
        font = small = ImageFont.load_default()
    Z = 4
    W = 1660
    sheet = Image.new("RGBA", (W, 2400), (30, 33, 42, 255))
    d = ImageDraw.Draw(sheet)
    d.text((12, 8), "EBB effects  -  Stage 15  -  2-3 colours, no outline, never scaled", fill=P.rgb("SALT_WHITE"), font=font)
    y = 30
    cells = {
        "fx_slash": 48, "fx_slash_warm": 48, "fx_stab": (24, 8), "fx_spark": 12, "fx_crack": 24,
        "fx_ring16": 16, "fx_ring32": 32, "fx_ring96": 96, "fx_lit": 24, "fx_stun": (16, 8), "fx_bleed": 8,
    }
    tints = {"fx_ring16": "SALT_RED", "fx_ring32": "SEA_PALE", "fx_ring96": "WARM_YELLOW"}
    for name, im in built.items():
        cw, ch = cells[name] if isinstance(cells[name], tuple) else (cells[name], cells[name])
        n = im.width // cw
        d.text((12, y), "%s  %d x %dx%d%s" % (name, n, cw, ch, "  (tinted %s)" % tints[name].replace("_", " ").lower() if name in tints else ""),
               fill=P.rgb("PALE_SLATE"), font=small)
        y += 12
        x = 12
        for bgk in ("SAND", "SEA"):
            for i in range(n):
                fr = im.crop((i * cw, 0, (i + 1) * cw, ch))
                if name in tints:
                    t = P.rgb(tints[name])
                    fr = Image.merge("RGBA", [fr.getchannel("A").point(lambda v, c=c: c) for c in t] + [fr.getchannel("A")])
                bg = Image.new("RGBA", (cw, ch), P.rgba(bgk))
                bg.alpha_composite(fr)
                zz = 2 if cw >= 96 else Z
                sheet.alpha_composite(zoom(bg, zz), (x, y))
                x += cw * zz + 6
            x += 18
        y += (ch * (2 if cw >= 96 else Z)) + 10

    # in place: the arc on Tam aiming right and up-left; the spark and crack on a shellback;
    # LIT and STUN over a shellback; bleed
    d.text((12, y), "in place at 3x: arc (gaff right, lantern up-left), spark and crack on a hit, LIT, STUN, BLEED", fill=P.rgb("PALE_SLATE"), font=small)
    y += 14
    tam = Image.open(os.path.join(SPRITES, "player.png")).convert("RGBA").crop((0, 0, 24, 24))
    shell = Image.open(os.path.join(SPRITES, "shellback.png")).convert("RGBA").crop((0, 0, 24, 24))
    gaff = Image.open(os.path.join(SPRITES, "gaff_hook.png")).convert("RGBA")

    def scene(w=72, h=72):
        return Image.new("RGBA", (w, h), P.rgba("SAND"))

    def put_rot(dst, im, angle, pivot, at, flip_v=False):
        w = im.transpose(Image.FLIP_TOP_BOTTOM) if flip_v else im
        cw = 2 * (w.width + 8)
        can = blank(cw, cw)
        can.alpha_composite(w, (cw // 2 - pivot[0], cw // 2 - pivot[1]))
        rot = can.rotate(-angle, resample=Image.NEAREST, center=(cw // 2, cw // 2))
        dst.alpha_composite(rot, (at[0] - cw // 2, at[1] - cw // 2))

    mocks = []
    for angle, sheet_key in ((0, "fx_slash"), (225, "fx_slash_warm")):
        for f in range(4):
            s = scene()
            mirror = 90 < angle < 270
            s.alpha_composite(tam.transpose(Image.FLIP_LEFT_RIGHT) if mirror else tam, (24, 24))
            put_rot(s, gaff, angle, (0, 4), (36, 39), mirror)
            fr = built[sheet_key].crop((f * 48, 0, (f + 1) * 48, 48))
            put_rot(s, fr, angle, (4, 24), (36, 39), mirror)
            mocks.append(s)
    for f in range(3):
        s = scene()
        s.alpha_composite(shell, (24, 24))
        s.alpha_composite(built["fx_spark"].crop((f * 12, 0, (f + 1) * 12, 12)), (30, 27))
        mocks.append(s)
    for f in range(4):
        s = scene()
        s.alpha_composite(shell, (24, 24))
        s.alpha_composite(built["fx_crack"].crop((f * 24, 0, (f + 1) * 24, 24)), (24, 21))
        mocks.append(s)
    for f in range(2):
        s = scene()
        s.alpha_composite(shell, (24, 24))
        s.alpha_composite(built["fx_lit"].crop((f * 24, 0, (f + 1) * 24, 24)), (24, 24))
        mocks.append(s)
    for f in range(2):
        s = scene()
        s.alpha_composite(shell, (24, 24))
        s.alpha_composite(built["fx_stun"].crop((f * 16, 0, (f + 1) * 16, 8)), (28, 18))
        mocks.append(s)
    for f in range(2):
        s = scene()
        s.alpha_composite(shell, (24, 24))
        s.alpha_composite(built["fx_bleed"].crop((f * 8, 0, (f + 1) * 8, 8)), (32, 30))
        mocks.append(s)
    x = 12
    for m in mocks:
        if x + 72 * 3 > W:
            x = 12
            y += 72 * 3 + 6
        sheet.alpha_composite(zoom(m, 3), (x, y))
        x += 72 * 3 + 6
    y += 72 * 3 + 16
    sheet = sheet.crop((0, 0, W, y))
    sheet.convert("RGB").save(os.path.join(REF, "fx_sheet.png"))
    print("wrote %s, fx_sheet.png" % ", ".join(built.keys()))


if __name__ == "__main__":
    main()
