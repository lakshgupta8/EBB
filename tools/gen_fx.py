def rgba(key, a=255):
    return P.rgb(key) + (a,)


def blank(w, h):
    return Image.new("RGBA", (w, h), (0, 0, 0, 0))


def strip(frames):
    w, h = frames[0].size
    out = blank(w * len(frames), h)
    for i, f in enumerate(frames):
        out.alpha_composite(f, (i * w, 0))
    return out


# --- the melee arc ---------------------------------------------------------------------
# The cell is 48x48 with the swing's pivot at its left-centre (4, 24): the engine spawns it
# on Tam's hand, turned to the aim, and mirrors it for the return swing.  The crescent's
# convex side faces the aim; its middle is 3 px thick and its tips 1 px.

def arc_frame(core, edge, f):
    """f: 0 a short thick start high on the arc, 1 the full crescent, 2 thinner, 3 three
    dashes.  Radius 20 about the pivot; the arc spans -70 to +70 degrees."""
    im = blank(48, 48)
    px = im.load()
    cx, cy = 4.0, 24.0
    r = 19.0
    if f == 0:
        span = (-70, -10)
    elif f == 3:
        span = (-70, 70)
    else:
        span = (-70, 70)
    cells = {}
    steps = 240
    for i in range(steps + 1):
        a = math.radians(span[0] + (span[1] - span[0]) * i / steps)
        # thickness: 3 px at the middle, 1 px at the tips (frame 2 thins by one)
        mid = 1.0 - abs(a) / math.radians(70)
        thick = 1 + 2 * mid if f in (0, 1) else 1 + 1.4 * mid
        if f == 3:
            # three dashes: keep only the middles of three bands
            band = (span[1] - span[0]) / 3.0
            pos = (math.degrees(a) - span[0]) % band
            if pos < band * 0.3 or pos > band * 0.7:
                continue
            thick = 1.0
        for t in range(int(round(thick))):
            rr = r - t
            x = int(round(cx + math.cos(a) * rr))
            y = int(round(cy + math.sin(a) * rr))
            if 0 <= x < 48 and 0 <= y < 48:
                # the outer pixel is the core, inner ones the edge
                cells.setdefault((x, y), t)
    for (x, y), t in cells.items():
        px[x, y] = core if t == 0 else edge
    return im


def build_arc(core_key, edge_key):
    core, edge = rgba(core_key), rgba(edge_key)
    return strip([arc_frame(core, edge, f) for f in range(4)])


