# --- the crack --------------------------------------------------------------------------
def crack_frame(f):
    """A ring of six shards flying out from the centre: Salt white heads, Bone tails."""
    im = blank(24, 24)
    px = im.load()
    head = rgba("SALT_WHITE")
    tail = rgba("BONE")
    cx, cy = 11.5, 11.5
    dist = [3.0, 6.0, 9.0, 11.0][f]
    length = [1, 3, 3, 2][f]
    for k in range(6):
        a = math.radians(k * 60 + 15)
        dx, dy = math.cos(a), math.sin(a)
        for t in range(length):
            d = dist - t
            x = int(round(cx + dx * d))
            y = int(round(cy + dy * d))
            if 0 <= x < 24 and 0 <= y < 24:
                px[x, y] = head if t == 0 else tail
    if f == 0:
        # the point of impact itself
        for (x, y) in ((11, 11), (12, 11), (11, 12), (12, 12)):
            px[x, y] = head
    return im


# --- rings --------------------------------------------------------------------------------
def ring_frame(size, f):
    """A 2 px ring thinning to 1 px, growing from 70 % to 100 % of the cell.  Salt white; the
    engine tints it."""
    im = blank(size, size)
    px = im.load()
    c = (size - 1) / 2.0
    rmax = size / 2.0 - 1.0
    r = rmax * (0.7 + 0.15 * f)
    thick = 2.0 if f < 2 else 1.0
    col = rgba("SALT_WHITE")
    for y in range(size):
        for x in range(size):
            d = math.hypot(x - c, y - c)
            if r - thick < d <= r:
                px[x, y] = col
    return im


