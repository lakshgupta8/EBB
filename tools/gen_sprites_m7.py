def build_props_m7(base):
    n0 = base.width // 16
    im = Image.new("RGBA", (16 * (n0 + len(PROP_ORDER_M7)), 16), (0, 0, 0, 0))
    im.alpha_composite(base, (0, 0))
    for i, n in enumerate(PROP_ORDER_M7):
        c = Canvas(16, 16)
        c.blit(PROPS_M7[n], 0, 0)
        im.alpha_composite(c.im, (16 * (n0 + i), 0))
    im.save(os.path.join(OUT, "props.png"))
    return im


def build_pickups_m7(base):
    n0 = base.width // 8
    im = Image.new("RGBA", (8 * (n0 + len(PICKUP_ORDER_M7)), 8), (0, 0, 0, 0))
    im.alpha_composite(base, (0, 0))
    for i, n in enumerate(PICKUP_ORDER_M7):
        c = Canvas(8, 8)
        c.blit(PICKUPS_M7[n], 0, 0)
        im.alpha_composite(c.im, (8 * (n0 + i), 0))
    im.save(os.path.join(OUT, "pickups.png"))
    return im


def build_dock():
    c = Canvas(48, 16)
    c.blit(DOCK, 0, 0)
    c.im.save(os.path.join(OUT, "dock.png"))
    return c.im


def build_coats(player):
    out = {}
    for name, swap in COATS.items():
        im = player.copy()
        px = im.load()
        for y in range(im.height):
            for x in range(im.width):
                r, g, b, a = px[x, y]
                if a and (r, g, b) in swap:
                    px[x, y] = swap[(r, g, b)] + (a,)
        im.save(os.path.join(OUT, "player_%s.png" % name))
        out["player_" + name] = im
    return out


def build_all(built):
    PAL.update(M7_PAL)
    built["props"] = build_props_m7(built["props"])
    built["pickups"] = build_pickups_m7(built["pickups"])
    built["dock"] = build_dock()
    built.update(build_coats(built["player"]))
    return built
