def fix_widths():
    for name, txt in ROOMS.items():
        rows = txt.strip("\n").split("\n")
        if len(rows) != 22:
            raise SystemExit("%s has %d rows" % (name, len(rows)))
        for i, r in enumerate(rows):
            if len(r) != 40:
                raise SystemExit("%s row %d is %d wide: %r" % (name, i, len(r), r))
