def shade_frame(legs, bob=0, strike=False, hurt=False):
    c = Canvas()
    head = G.HEAD.replace("h", "D").replace("H", "D").replace("f", "D").replace("F", "D").replace("e", "E")
    torso = G.TORSO.replace("C", "D").replace("c", "D").replace("f", "D").replace("b", "D")
    lg = legs.replace("c", "D").replace("b", "D")
    c.blit(lg, 7, 18 + bob)
    c.blit(torso, 6, 12 + bob)
    c.blit(head, 6, 4 + bob)
    if strike:
        c.blit("kEEEEEk", 16, 14 + bob)
    if hurt:
        c.blit("kEk", 9, 8 + bob)
    return c


