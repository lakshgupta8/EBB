def build_beacon():
    """24x24 pool of light for the Storm Lantern's beacon."""
    size = 24
    c = Canvas(size, size)
    cx = cy = size / 2 - 0.5
    for y in range(size):
        for x in range(size):
            d = math.hypot(x - cx, y - cy) / 11.0
            if d <= 1.0:
                a = int(200 * (1.0 - d * d))
                c.px(x, y, "Y" if d < 0.3 else "y", a)
    c.im.save(os.path.join(OUT, "beacon.png"))
    return c.im


