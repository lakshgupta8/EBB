TILE_NAMES_M4B = ["basalt", "basalt2", "hallwall", "hallwall2", "channel", "dais"]


def build_tiles_m4b(base):
    n0 = base.width // 16
    im = Image.new("RGBA", (16 * (n0 + len(TILE_NAMES_M4B)), 16), (0, 0, 0, 0))
    im.alpha_composite(base, (0, 0))
    bas = (52, 56, 70); bas_l = (74, 80, 96); bas_d = (34, 36, 48)
    wall = (30, 34, 48); wall_l = (58, 66, 88); wall_d = (16, 18, 28); wall_g = (60, 120, 130)
    chan = (36, 48, 66); chan_l = (52, 70, 92); chan_d = (24, 30, 44)
    dais = (96, 92, 110); dais_l = (128, 122, 142); dais_d = (62, 58, 74)
    G._noise_tile(im, 16 * n0, bas, bas_l, bas_d, 80, 0.08, 0.1)
    G._noise_tile(im, 16 * (n0 + 1), bas, bas_l, bas_d, 81, 0.08, 0.1)
    # big dressed blocks with a faint glow-line of kelp between them
    for v in range(2):
        ox = 16 * (n0 + 2 + v)
        random.seed(90 + v)
        for y in range(16):
            for x in range(16):
                bx = (x + (8 if (y // 8) % 2 else 0)) % 16
                c = wall
                if y % 8 == 7 or bx == 15:
                    c = wall_d
                elif random.random() < 0.06:
                    c = wall_l
                elif (y % 8 == 6 and random.random() < 0.25):
                    c = wall_g
                im.putpixel((ox + x, y), c + (255,))
    G._noise_tile(im, 16 * (n0 + 4), chan, chan_l, chan_d, 92, 0.12, 0.12)
    random.seed(93)
    ox = 16 * (n0 + 5)
    for y in range(16):
        for x in range(16):
            c = dais
            if (x + y) % 8 == 0:
                c = dais_d
            elif random.random() < 0.08:
                c = dais_l
            im.putpixel((ox + x, y), c + (255,))
    im.save(os.path.join(OUT, "tiles.png"))
    return im


