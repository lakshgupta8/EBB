def shift(im, dx, dy):
    out = cell()
    out.alpha_composite(im.crop((max(0, -dx), max(0, -dy), CELL - max(0, dx), CELL - max(0, dy))), (max(0, dx), max(0, dy)))
    return out


def sub(text, table):
    for a, b in table.items():
        text = text.replace(a, b)
    return text


