def beam(w=256, h=48):
    """The lighthouse beam as a PointLight2D texture: bright and narrow at the lamp (x 0),
    widening and fading along its length. White; the light colours it."""
    im = Image.new("RGBA", (w, h), (255, 255, 255, 0))
    px = im.load()
    cy = (h - 1) / 2.0
    for x in range(w):
        t = x / (w - 1)
        half = 1.5 + 21.0 * t
        along = (1.0 - t) ** 1.1
        for y in range(h):
            d = abs(y - cy) / half
            if d <= 1.0:
                across = (1.0 - d) ** 0.8
                a = int(round(255 * along * across * 0.9))
                px[x, y] = (255, 255, 255, a)
    return im


def main():
    os.makedirs(REF, exist_ok=True)
    tiles = Image.open(os.path.join(SPRITES, "tiles.png")).convert("RGBA")
    assert tiles.width == 16 * 45, tiles.width
    new = [g16(t) for t in (DECK, DECK2, HULL_FACE, HULL_TOP, SILT, QUAY)]
    for i, t in enumerate(new):
        blank = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
        tiles.paste(blank, ((26 + i) * 16, 0))
        tiles.alpha_composite(t, ((26 + i) * 16, 0))
    tiles.save(os.path.join(SPRITES, "tiles.png"))
    decor = Image.new("RGBA", (16 * 8, 16), (0, 0, 0, 0))
    for i, n in enumerate(ORDER_HARBOUR):
        decor.alpha_composite(g16(DECOR_HARBOUR[n]), (i * 16, 0))
    decor.save(os.path.join(SPRITES, "decor4.png"))
    dock = grid(DOCK, 48, 16)
    dock.save(os.path.join(SPRITES, "dock.png"))
    vault = Image.new("RGBA", (48, 24), (0, 0, 0, 0))
    vault.alpha_composite(grid(VAULT, 24, 24), (0, 0))
    vault.alpha_composite(grid(VAULT_OPEN, 24, 24), (24, 0))
    vault.save(os.path.join(SPRITES, "prop_vault.png"))
    bm = beam()
    bm.save(os.path.join(SPRITES, "beam.png"))

    # review sheet
    try:
        font = ImageFont.load_default(size=11)
        small = ImageFont.load_default(size=9)
    except TypeError:
        font = small = ImageFont.load_default()
    Z = 4
    sheet = Image.new("RGBA", (1180, 620), (30, 33, 42, 255))
    d = ImageDraw.Draw(sheet)
    d.text((12, 8), "EBB harbour  -  Stage 19  -  tiles 26-31 (2x2 at 4x), a mock corner, decor4, the dock, the vault, the beam",
           fill=P.rgb("SALT_WHITE"), font=font)
    x, y = 12, 30
    for i, n in enumerate(("deck", "deck2", "hull face", "hull top", "silt", "quay")):
        t = new[i]
        block = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
        for by in (0, 16):
            for bx in (0, 16):
                block.alpha_composite(t, (bx, by))
        sheet.alpha_composite(zoom(block, Z), (x, y))
        d.text((x, y + 32 * Z + 2), "%d %s" % (26 + i, n), fill=P.rgb("PALE_SLATE"), font=small)
        x += 32 * Z + 12
    # a mock corner: hull top over hull face over deck, silt and quay patches, decor on it
    mock = Image.new("RGBA", (16 * 10, 16 * 6), (0, 0, 0, 0))
    for cx in range(10):
        mock.alpha_composite(new[3], (cx * 16, 0))
        mock.alpha_composite(new[2], (cx * 16, 16))
        for cy in range(2, 6):
            k = 0 if (cx * 7 + cy * 13) % 5 else 1
            tile = new[k]
            if cx >= 7 and cy >= 4:
                tile = new[4]
            if cx <= 1 and cy >= 3:
                tile = new[5]
            mock.alpha_composite(tile, (cx * 16, cy * 16))
    for i, (n, cx, cy) in enumerate((("rope", 3, 2), ("crate", 5, 3), ("bollard", 2, 2), ("netting", 6, 4), ("plank", 4, 5),
                                      ("chain", 8, 2), ("anchor", 7, 3), ("hook", 9, 4))):
        mock.alpha_composite(g16(DECOR_HARBOUR[n]), (cx * 16, cy * 16))
    mock.alpha_composite(dock, (16, 64))
    mock.alpha_composite(grid(VAULT, 24, 24), (100, 44))
    sheet.alpha_composite(zoom(mock, 3), (x + 12, y))
    y += 32 * Z + 30
    d.text((12, y), "decor4.png over deck (4x); dock 48x16, prop_vault 2 x 24x24 (4x); beam.png 256x48 over Night 1 (1x)", fill=P.rgb("PALE_SLATE"), font=small)
    y += 14
    x = 12
    for n in ORDER_HARBOUR:
        bg = Image.new("RGBA", (16, 16), P.rgba("WOOD"))
        bg.alpha_composite(g16(DECOR_HARBOUR[n]))
        sheet.alpha_composite(zoom(bg, Z), (x, y))
        d.text((x, y + 16 * Z + 2), n, fill=P.rgb("PALE_SLATE"), font=small)
        x += 16 * Z + 8
    y += 16 * Z + 20
    x = 12
    for im, bgk in ((dock, "SAND_DARK"), (vault, "WOOD")):
        bg = Image.new("RGBA", im.size, P.rgba(bgk))
        bg.alpha_composite(im)
        sheet.alpha_composite(zoom(bg, Z), (x, y))
        x += im.width * Z + 16
    bg = Image.new("RGBA", bm.size, P.rgba("NIGHT_1"))
    warm = P.rgb("WARM_YELLOW")
    tinted = Image.new("RGBA", bm.size, warm + (0,))
    tinted.putalpha(bm.getchannel("A"))
    bg.alpha_composite(tinted)
    sheet.alpha_composite(bg, (x, y))
