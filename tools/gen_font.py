def main():
    os.makedirs(OUT, exist_ok=True)
    chars = sorted(G.keys(), key=ord)
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    w, h = cols * CELL_W, rows * CELL_H
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    lines = [
        'info face="ebb" size=8 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0 outline=0',
        f"common lineHeight={LINE_HEIGHT} base=7 scaleW={w} scaleH={h} pages=1 packed=0 alphaChnl=0 redChnl=0 greenChnl=0 blueChnl=0",
        'page id=0 file="ebb.png"',
        f"chars count={len(chars)}",
    ]
    for i, ch in enumerate(chars):
        cx, cy = (i % cols) * CELL_W, (i // cols) * CELL_H
        for y, row in enumerate(G[ch]):
            for x, px in enumerate(row):
                if px == "#":
                    im.putpixel((cx + x, cy + y), (255, 255, 255, 255))
        lines.append(
            f"char id={ord(ch)} x={cx} y={cy} width={CELL_W} height={CELL_H} xoffset=0 yoffset=0 xadvance={CELL_W} page=0 chnl=15"
        )
    im.save(os.path.join(OUT, "ebb.png"))
    with open(os.path.join(OUT, "ebb.fnt"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote ebb.fnt/ebb.png with {len(chars)} glyphs ({w}x{h})")


if __name__ == "__main__":
    main()
