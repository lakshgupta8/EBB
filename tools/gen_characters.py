def strip(frames):
    im = Image.new("RGBA", (CELL * len(frames), CELL), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        im.alpha_composite(f, (i * CELL, 0))
    return im


def main():
    os.makedirs(SPRITES, exist_ok=True)
    os.makedirs(REF, exist_ok=True)
    tam = build_tam()
    sheets = {"player": strip(tam)}
    oil = [P.rgb(k) for k in ("OILSKIN_DARK", "OILSKIN", "OILSKIN_LIGHT")]
    for name, ramp in COATS.items():
        swap = {oil[i]: P.rgb(ramp[i]) for i in range(3)}
        sheets["player_" + name] = recolour(sheets["player"], swap)
    sheets["npc_maren"] = strip(build_maren())
    sheets["npc_bram"] = strip([BRAM, BRAM_2])
    for name, im in sheets.items():
        im.save(os.path.join(SPRITES, name + ".png"))

    # review sheet
    try:
        font = ImageFont.load_default(size=11)
        small = ImageFont.load_default(size=9)
    except TypeError:
        font = small = ImageFont.load_default()
    labels = ["idle"] * 4 + ["walk"] * 6 + ["hurt"] * 2 + ["dash"] * 2 + ["death"] * 4
    rows = [("Tam (player.png)", sheets["player"], labels),
            ("Tam: fisher coat", sheets["player_fisher"], labels),
            ("Tam: verger coat", sheets["player_verger"], labels),
            ("Tam: harbour coat", sheets["player_harbour"], labels),
            ("Maren (npc_maren.png)", sheets["npc_maren"], ["idle", "breath"]),
            ("Bram, drowned (npc_bram.png)", sheets["npc_bram"], ["idle", "drip"])]
    W = 12 + 18 * (CELL * 4 + 4) + 12
    sheet = Image.new("RGBA", (W, 12 + len(rows) * (CELL * 4 + 40)), (30, 33, 42, 255))
    d = ImageDraw.Draw(sheet)
    y = 8
    for title, im, labs in rows:
        d.text((12, y), title, fill=P.rgb("SALT_WHITE"), font=font)
        y += 14
        n = im.width // CELL
        for i in range(n):
            f = im.crop((i * CELL, 0, (i + 1) * CELL, CELL))
            bg = Image.new("RGBA", (CELL, CELL), P.rgba("SAND"))
            bg.alpha_composite(f)
            sheet.alpha_composite(zoom(bg, 4), (12 + i * (CELL * 4 + 4), y))
            d.text((12 + i * (CELL * 4 + 4), y + CELL * 4 + 2), "%d %s" % (i, labs[i]), fill=P.rgb("PALE_SLATE"), font=small)
        y += CELL * 4 + 24
    sheet.convert("RGB").save(os.path.join(REF, "characters_sheet.png"))
    print("wrote", ", ".join(sheets), "and characters_sheet.png")


if __name__ == "__main__":
    main()
