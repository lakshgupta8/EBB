def build_tam():
    frames = []
    # idle 4 @ 3 fps: settle, breathe out (down 1), settle, the lantern sways
    frames.append(tam_frame())
    frames.append(tam_frame(dy=1))
    frames.append(tam_frame())
    frames.append(tam_frame(lantern_d=(0, 1)))
    # walk 6 @ 10 fps: contact, down, pass, contact, down, pass
    frames.append(tam_frame(torso=TORSO_R_FWD, legs=LEGS_W1))
    frames.append(tam_frame(torso=TORSO_R_FWD, legs=LEGS_W2, dy=1, lantern_d=(0, 1)))
    frames.append(tam_frame(torso=TORSO, legs=LEGS_W3))
    frames.append(tam_frame(torso=TORSO_L_FWD, legs=LEGS_W1))
    frames.append(tam_frame(torso=TORSO_L_FWD, legs=LEGS_W2, dy=1, lantern_d=(0, 1)))
    frames.append(tam_frame(torso=TORSO, legs=LEGS_W6))
    # hurt 2 @ 8 fps: recoil back 2 px, hood flies; then settle with the mouth still tight
    frames.append(tam_frame(head=HEAD_HURT, head_dx=-2, torso_dx=-1, lantern_d=(1, 0)))
    frames.append(tam_frame(head=HEAD_HURT))
    # dash 2 @ 12 fps: stretched lean, coat trails
    frames.append(tam_frame(torso=TORSO_DASH, legs=LEGS_DASH, head_dx=2, torso_dx=1, lantern_d=(-2, 0)))
    frames.append(tam_frame(torso=TORSO_DASH, legs=LEGS_DASH, head_dx=1, lantern_d=(-1, 0)))
    # death 4 @ 6 fps: knee, fall, lie, still
    frames.append(stack((DEATH_1, 0, 0), (LANTERN, LX, LY + 2)))
    frames.append(stack((DEATH_2, 0, 0), (LANTERN, 0, 14)))
    frames.append(stack((DEATH_3, 0, 0), (LANTERN, 19, 5)))
    frames.append(stack((DEATH_4, 0, 0), (LANTERN, 19, 6)))
    assert len(frames) == 18
    return frames


