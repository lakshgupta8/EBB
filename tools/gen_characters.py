def part(text):
    """A grid whose rows may be shorter than 24; padded to 24 wide, height = rows."""
    rows = text.strip("\n").split("\n")
    for i, r in enumerate(rows):
        assert len(r) <= 24, "row %d is %d wide" % (i, len(r))
    return grid("\n".join(r.ljust(24, ".") for r in rows))


def cell():
    return Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))


def stack(*layers):
    """layers: (image, x, y) drawn in order into a 24x24 cell."""
    im = cell()
    for img, x, y in layers:
        im.alpha_composite(img, (x, y))
    return im


