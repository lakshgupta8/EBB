CELL = 24


def g24(text):
    rows = text.strip("\n").split("\n")
    assert len(rows) == 24, "%d rows" % len(rows)
    for i, r in enumerate(rows):
        assert len(r) == 24, "row %d is %d wide" % (i, len(r))
    return grid(text, 24, 24)


def g16(text):
    rows = text.strip("\n").split("\n")
    assert len(rows) == 16, "%d rows" % len(rows)
    for i, r in enumerate(rows):
        assert len(r) == 16, "row %d is %d wide" % (i, len(r))
    return grid(text, 16, 16)


def breathe(im, split=17):
    """The living: everything above the legs drops one pixel."""
    out = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
    out.alpha_composite(im.crop((0, split, CELL, CELL)), (0, split))
    out.alpha_composite(im.crop((0, 0, CELL, split)), (0, 1))
    return out


def drip(im, x, y):
    """The drowned: a Sea pale drop falling from the hem."""
    out = im.copy()
    out.putpixel((x, y), P.rgb("SEA_PALE") + (255,))
    return out


def strip(frames, w=CELL, h=CELL):
    im = Image.new("RGBA", (w * len(frames), h), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        im.alpha_composite(f, (i * w, 0))
    return im


