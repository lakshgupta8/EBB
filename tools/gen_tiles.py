def build_icons():
    out = []
    for name in ICON_ORDER:
        im = grid(BOARD, 24, 24)
        im.alpha_composite(grid(BOARD_INNER, 12, 12), (6, 6))
        im.alpha_composite(grid(SYMBOLS[name], 12, 12), (6, 6))
        out.append(im)
    return strip(out, 24, 24)


def main():
    os.makedirs(REF, exist_ok=True)
    old_tiles = Image.open(os.path.join(SPRITES, "tiles.png")).convert("RGBA")
    tiles = build_tiles(old_tiles)
    tiles.save(os.path.join(SPRITES, "tiles.png"))
    sheets = {
        "decor": strip([g16(DECOR_FLATS[n]) for n in ORDER_FLATS], 16, 16),
        "decor2": strip([g16(DECOR_STREETS[n]) for n in ORDER_STREETS], 16, 16),
        "decor3": strip([g16(DECOR_HALL[n]) for n in ORDER_HALL], 16, 16),
        "prop_fountain": grid(FOUNTAIN, 32, 32),
        "prop_altar": grid(ALTAR, 24, 32),
        "prop_cage": strip([grid(CAGE, 24, 24), grid(CAGE_OPEN, 24, 24)], 24, 24),
        "lighthouse": grid(LIGHTHOUSE, 32, 48),
        # door.png is written by gen_water.py (these two arches plus four water states).
        "icons": build_icons(),
    }
    props = Image.open(os.path.join(SPRITES, "props.png")).convert("RGBA")
    for idx, text in ((1, CHEST), (2, CHEST_OPEN), (20, LANTERN_POST)):
        cellim = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
        cellim.alpha_composite(g16(text))
        props.paste(cellim, (idx * 16, 0))
    sheets["props"] = props
    for name, im in sheets.items():
        im.save(os.path.join(SPRITES, name + ".png"))

    # --- review sheet ---
    try:
        font = ImageFont.load_default(size=11)
        small = ImageFont.load_default(size=9)
    except TypeError:
        font = small = ImageFont.load_default()
    names = ["sand", "sand2", "wall face", "wall top", "water", "water2", "deep", "low", "raised", "door", "door open",
             "rock", "foam", "foam2", "cobble", "cobble2", "ruin face", "ruin top", "moss", "flag", "basalt", "basalt2",
             "hall face", "hall top", "channel", "dais", "deck*", "deck2*", "hull*", "hull2*", "silt*", "quay*",
             "hub sand", "hub sand2", "hub wall face", "hub wall top", "hub low", "hub raised",
             "shade S", "W", "E", "SW", "SE", "WE", "SWE"]
    Z = 4
    W = 1180
    sheet = Image.new("RGBA", (W, 1500), (30, 33, 42, 255))
    d = ImageDraw.Draw(sheet)
    d.text((12, 8), "EBB environment  -  Stage 09  -  tiles (2x2 of each), decor, props, doors, signboards at 4x", fill=P.rgb("SALT_WHITE"), font=font)
    x, y = 12, 30
    for i, n in enumerate(names):
        t = tiles.crop((i * 16, 0, (i + 1) * 16, 16))
        block = Image.new("RGBA", (32, 32), P.rgba("STONE") if i >= 38 else (0, 0, 0, 0))
        for by in (0, 16):
            for bx in (0, 16):
                block.alpha_composite(t, (bx, by))
        sheet.alpha_composite(zoom(block, Z), (x, y))
        d.text((x, y + 32 * Z + 2), "%d %s" % (i, n), fill=P.rgb("PALE_SLATE"), font=small)
        x += 32 * Z + 12
        if x + 32 * Z > W:
            x = 12
            y += 32 * Z + 22
    y += 32 * Z + 30
    floors = {"decor": "SAND", "decor2": "STONE", "decor3": "BASALT"}
    for name in ("decor", "decor2", "decor3"):
        d.text((12, y), name, fill=P.rgb("SALT_WHITE"), font=font)
        y += 14
        for i in range(8):
            bg = Image.new("RGBA", (16, 16), P.rgba(floors[name]))
            bg.alpha_composite(sheets[name].crop((i * 16, 0, (i + 1) * 16, 16)))
            sheet.alpha_composite(zoom(bg, Z), (12 + i * (16 * Z + 8), y))
        y += 16 * Z + 16
    d.text((12, y), "props: fountain 32x32, altar 24x32, cage 48x24, chest / open / lantern post 16, lighthouse 32x48, door 64x32", fill=P.rgb("SALT_WHITE"), font=font)
    y += 14
    x = 12
    sheets["door"] = strip([grid(DOOR_SHUT, 32, 32), grid(DOOR_OPEN_FRAME, 32, 32)], 32, 32)
    for key, bgk in (("prop_fountain", "SAND_LIGHT"), ("prop_altar", "STONE"), ("prop_cage", "STONE"), ("lighthouse", "SAND_LIGHT"), ("door", "SAND")):
        im = sheets[key]
        bg = Image.new("RGBA", im.size, P.rgba(bgk))
        bg.alpha_composite(im)
        sheet.alpha_composite(zoom(bg, Z), (x, y))
        x += im.width * Z + 12
    for idx in (1, 2, 20):
        bg = Image.new("RGBA", (16, 16), P.rgba("SAND_LIGHT"))
        bg.alpha_composite(props.crop((idx * 16, 0, (idx + 1) * 16, 16)))
        sheet.alpha_composite(zoom(bg, Z), (x, y))
        x += 16 * Z + 8
    y += 48 * Z + 16
    d.text((12, y), "signboards", fill=P.rgb("SALT_WHITE"), font=font)
    y += 14
    for i, n in enumerate(ICON_ORDER):
        bg = Image.new("RGBA", (24, 24), P.rgba("STONE_DARK"))
        bg.alpha_composite(sheets["icons"].crop((i * 24, 0, (i + 1) * 24, 24)))
        sheet.alpha_composite(zoom(bg, Z), (12 + i * (24 * Z + 8), y))
        d.text((12 + i * (24 * Z + 8), y + 24 * Z + 2), n, fill=P.rgb("PALE_SLATE"), font=small)
    y += 24 * Z + 30
    sheet = sheet.crop((0, 0, W, y))
    sheet.convert("RGB").save(os.path.join(REF, "environment_sheet.png"))
    print("wrote tiles.png (45), decor x3, props, prop_fountain/altar/cage, lighthouse, door, icons, environment_sheet.png")


if __name__ == "__main__":
    main()
