def flat(key, w=16, h=16):
    return Image.new("RGBA", (w, h), P.rgba(key))


def strip(images, w, h):
    im = Image.new("RGBA", (w * len(images), h), (0, 0, 0, 0))
    for i, f in enumerate(images):
        im.alpha_composite(f, (i * w, 0))
    return im


