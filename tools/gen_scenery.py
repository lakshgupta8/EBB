def poly(im, pts, fill=N1):
    ImageDraw.Draw(im).polygon(pts, fill=fill)


def box(im, x0, y0, x1, y1, fill=N1):
    ImageDraw.Draw(im).rectangle([x0, y0, x1, y1], fill=fill)


def curve(im, x0, y0, x1, y1, bend, width=2, fill=N1):
    """A quadratic arc from (x0, y0) to (x1, y1) bowing by `bend` px, drawn one column at a
    time so the runs stay monotone."""
    px = im.load()
    steps = max(abs(x1 - x0), abs(y1 - y0)) * 2
    last = None
    for i in range(steps + 1):
        t = i / steps
        x = x0 + (x1 - x0) * t
        y = y0 + (y1 - y0) * t
        # bow perpendicular to the chord
        dx, dy = x1 - x0, y1 - y0
        ln = (dx * dx + dy * dy) ** 0.5 or 1
        nx, ny = -dy / ln, dx / ln
        k = 4 * bend * t * (1 - t)
        cx, cy = int(round(x + nx * k)), int(round(y + ny * k))
        if (cx, cy) == last:
            continue
        last = (cx, cy)
        for wx in range(width):
            for wy in range(width):
                xx, yy = cx + wx, cy + wy
                if 0 <= xx < im.width and 0 <= yy < im.height:
                    px[xx, yy] = fill


def sky_edge(im, top=N2, body=N1):
    """Every body pixel with nothing above it catches the sky."""
    px = im.load()
    for y in range(im.height):
        for x in range(im.width):
            if px[x, y] == body and (y == 0 or px[x, y - 1][3] == 0):
                px[x, y] = top
    return im


def wreck_ribs():
    im = sil(40, 24)
    box(im, 3, 21, 36, 23)                      # keel
    for i, x in enumerate((6, 13, 20, 27, 34)):
        top = (5, 3, 2, 4, 7)[i]
        curve(im, x, 21, x - 4, top, -3)
    return im


def dune():
    im = sil(48, 12)
    poly(im, [(0, 11), (10, 5), (20, 2), (30, 2), (40, 6), (47, 11)])
    return im


def village_roofs():
    im = sil(48, 32)
    # house A: walls, gable, chimney, a dark window
    box(im, 2, 18, 22, 31)
    poly(im, [(1, 18), (12, 7), (23, 18)])
    box(im, 17, 10, 19, 17)
    box(im, 10, 22, 12, 25, AB)
    # house B: lower, broken ridge
    box(im, 26, 20, 46, 31)
    poly(im, [(25, 20), (36, 12), (47, 20)])
    box(im, 34, 24, 36, 27, AB)
    box(im, 37, 12, 38, 14, (0, 0, 0, 0))       # a slipped ridge tile
    return im


def chapel():
    im = sil(24, 44)
    box(im, 3, 28, 20, 43)                      # nave
