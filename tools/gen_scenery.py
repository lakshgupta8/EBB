def chain_hang():
    im = sil(8, 48)
    for i in range(0, 40, 4):
        if (i // 4) % 2 == 0:
            box(im, 3, i, 4, i + 3)
        else:
            box(im, 2, i, 5, i + 3)
            box(im, 3, i + 1, 4, i + 2, (0, 0, 0, 0))
    box(im, 3, 40, 4, 43)
    curve(im, 1, 47, 6, 42, 2, 2)              # the hook
    return im


def great_arch():
    im = sil(48, 40)
    box(im, 2, 14, 9, 39)
    box(im, 38, 14, 45, 39)
    curve(im, 4, 14, 24, 2, 0, 4)
    curve(im, 24, 2, 44, 14, 0, 4)
