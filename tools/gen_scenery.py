def place(im, cw, ch):
    out = Image.new("RGBA", (cw, ch), (0, 0, 0, 0))
    out.alpha_composite(im, ((cw - im.width) // 2, ch - im.height))
    return out


def main():
    os.makedirs(REF, exist_ok=True)
    # the void
    beyond = Image.new("RGBA", (48, 48), (0, 0, 0, 0))
    for r, key in enumerate(VOID_ROWS):
        for c, marks in enumerate(VOID[key]):
            beyond.alpha_composite(void_tile(marks), (c * 16, r * 16))
    beyond.save(os.path.join(SPRITES, "beyond.png"))
    # far scenery
    pieces = []
    for name, build, biomes in SCENERY:
        im = build()
        if "deep" in biomes:
            im = sky_edge(im)
        else:
            px = im.load()
            for y in range(im.height):
                for x in range(im.width):
                    if px[x, y] == N1:
                        px[x, y] = N2
            im = sky_edge(im, top=SL, body=N2)
        pieces.append(place(im, CELL, CELL))
    scenery = Image.new("RGBA", (CELL * len(pieces), CELL), (0, 0, 0, 0))
    for i, p in enumerate(pieces):
        scenery.alpha_composite(p, (i * CELL, 0))
    scenery.save(os.path.join(SPRITES, "scenery.png"))
    # foreground
    fg = []
    for name, text, _ in FOREGROUND:
        im = sky_edge(grid(text, FG_W, FG_H), top=N1, body=INK)
        fg.append(im)
    fore = Image.new("RGBA", (FG_W * len(fg), FG_H), (0, 0, 0, 0))
    for i, p in enumerate(fg):
        fore.alpha_composite(p, (i * FG_W, 0))
    fore.save(os.path.join(SPRITES, "foreground.png"))

    # --- review sheet ---
    tiles = Image.open(os.path.join(SPRITES, "tiles.png")).convert("RGBA")
    try:
        font = ImageFont.load_default(size=11)
        small = ImageFont.load_default(size=9)
    except TypeError:
        font = small = ImageFont.load_default()
    W = 1400
    sheet = Image.new("RGBA", (W, 1400), (30, 33, 42, 255))
    d = ImageDraw.Draw(sheet)
    d.text((12, 8), "EBB depth  -  Stage 12  -  the void beyond the walls, far scenery, foreground silhouettes",
           fill=P.rgb("SALT_WHITE"), font=font)
    y = 30
    d.text((12, y), "beyond.png: sea / rubble / deep rows, empty / A / B variants (4x), then a 6x4 field of each row picked by hash (2x)",
           fill=P.rgb("PALE_SLATE"), font=small)
    y += 14
    sheet.alpha_composite(zoom(beyond, 4), (12, y))
    x = 12 + 48 * 4 + 20
    for r, key in enumerate(VOID_ROWS):
        field = Image.new("RGBA", (16 * 6, 16 * 4), AB)
        for ty in range(4):
            for tx in range(6):
                h = (tx * 73856093 ^ ty * 19349663 ^ (r + 1) * 83492791) % 100
                c = 0 if h < 40 else 1 if h < 72 else 2
                field.alpha_composite(beyond.crop((c * 16, r * 16, c * 16 + 16, r * 16 + 16)), (tx * 16, ty * 16))
        sheet.alpha_composite(zoom(field, 2), (x, y))
        d.text((x, y + 64 * 2 + 2), key, fill=P.rgb("PALE_SLATE"), font=small)
        x += 96 * 2 + 16
    y += 48 * 4 + 20

    d.text((12, y), "scenery.png over the void at 3x (Night 2 body with a Slate sky edge; the Hall's pieces Night 1 with a Night 2 edge; Abyss holes)", fill=P.rgb("PALE_SLATE"), font=small)
    y += 14
    x = 12
    for i, (name, _, biomes) in enumerate(SCENERY):
        bg = Image.new("RGBA", (CELL, CELL), AB)
        bg.alpha_composite(pieces[i])
        sheet.alpha_composite(zoom(bg, 3), (x, y))
        d.text((x, y + CELL * 3 + 2), "%d %s" % (i, name), fill=P.rgb("PALE_SLATE"), font=small)
        d.text((x, y + CELL * 3 + 12), ",".join(biomes), fill=P.rgb("WET_GREY"), font=small)
        x += CELL * 3 + 8
        if x + CELL * 3 > W:
            x = 12
            y += CELL * 3 + 30
    y += CELL * 3 + 34

    d.text((12, y), "foreground.png at 4x over the Flats wall top (Ink, Night 1 top edge); the last 4 px sit below the screen", fill=P.rgb("PALE_SLATE"), font=small)
    y += 14
    x = 12
    walltop = tiles.crop((3 * 16, 0, 4 * 16, 16))
    for i, (name, _, biomes) in enumerate(FOREGROUND):
        bg = Image.new("RGBA", (FG_W, FG_H), P.rgba("SAND"))
        bg.alpha_composite(walltop, (0, 8))
        bg.alpha_composite(fg[i])
        sheet.alpha_composite(zoom(bg, 4), (x, y))
        d.text((x, y + FG_H * 4 + 2), name, fill=P.rgb("PALE_SLATE"), font=small)
        x += FG_W * 4 + 10
    y += FG_H * 4 + 30

    # a mock of the hub's north edge: 6 rows of void with the village, the rim face, sand
